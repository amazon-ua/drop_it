def fmt(v, d=0):
    return f"{v:,.{d}f}".replace(",", " ")


def load_results(mode):
    p = OUT / f"opt_results_{mode}.json"
    if not p.exists():
        return []
    return [r for r in json.loads(p.read_text()) if "total" in r]


def analyse(sc, loads=None):
    an = C.Analysis(sc, loads or M.Loads()).run_all()
    return an


